-- =====================================================================
-- MécaDétect - V7 : archivage des anciennes interventions (UC-DB4, tâche 4.5)
--
-- PKG_MAINTENANCE.ARCHIVER_INTERVENTIONS déplace vers des tables d'archive
-- les interventions closes avant une date (terminées avant la date, ou
-- annulées sur une demande antérieure à la date), avec leur historique.
--
-- - Traitement par lots : BULK COLLECT des identifiants, puis FORALL pour
--   copier et supprimer ; un commit par lot, pour ne pas retenir un undo
--   énorme sur des centaines de milliers de lignes.
-- - Une intervention ouverte n'est jamais archivée, quelle que soit sa date.
-- - Chaque exécution est tracée dans JOURNAL_ARCHIVAGE, y compris en cas
--   d'erreur : le journal est écrit dans une transaction autonome, qui
--   survit à l'annulation du lot en échec.
-- =====================================================================

CREATE TABLE intervention_archive (
    id_intervention    NUMBER(10)     NOT NULL,
    numero             VARCHAR2(20)   NOT NULL,
    titre              VARCHAR2(100)  NOT NULL,
    description        VARCHAR2(1000) NOT NULL,
    priorite           VARCHAR2(10)   NOT NULL,
    statut             VARCHAR2(20)   NOT NULL,
    date_demande       TIMESTAMP      NOT NULL,
    date_planifiee     TIMESTAMP,
    date_debut         TIMESTAMP,
    date_fin           TIMESTAMP,
    temps_passe_min    NUMBER(6),
    compte_rendu       VARCHAR2(2000),
    motif_annulation   VARCHAR2(500),
    version            NUMBER(10)     NOT NULL,
    id_equipement      NUMBER(10)     NOT NULL,
    id_demandeur       NUMBER(10)     NOT NULL,
    id_technicien      NUMBER(10),
    id_modifie_par     NUMBER(10)     NOT NULL,
    date_archivage     TIMESTAMP      NOT NULL,
    CONSTRAINT pk_intervention_archive PRIMARY KEY (id_intervention)
);

CREATE TABLE historique_statut_archive (
    id_historique      NUMBER(10)   NOT NULL,
    ancien_statut      VARCHAR2(20),
    nouveau_statut     VARCHAR2(20) NOT NULL,
    date_changement    TIMESTAMP    NOT NULL,
    id_intervention    NUMBER(10)   NOT NULL,
    id_auteur          NUMBER(10)   NOT NULL,
    CONSTRAINT pk_historique_statut_archive PRIMARY KEY (id_historique),
    CONSTRAINT fk_historique_archive_intervention
        FOREIGN KEY (id_intervention) REFERENCES intervention_archive (id_intervention)
);

CREATE INDEX idx_historique_archive_intervention ON historique_statut_archive (id_intervention);

CREATE TABLE journal_archivage (
    id_journal         NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    date_debut         TIMESTAMP      NOT NULL,
    date_fin           TIMESTAMP,
    date_limite        DATE,
    interventions      NUMBER(10)     DEFAULT 0 NOT NULL,
    historiques        NUMBER(10)     DEFAULT 0 NOT NULL,
    statut             VARCHAR2(10)   NOT NULL,
    message            VARCHAR2(4000),
    CONSTRAINT pk_journal_archivage PRIMARY KEY (id_journal),
    CONSTRAINT ck_journal_archivage_statut CHECK (statut IN ('EN_COURS', 'SUCCES', 'ECHEC'))
);

CREATE OR REPLACE PACKAGE pkg_maintenance AS

    -- p_date_limite   : sont archivées les interventions terminées avant cette date,
    --                   et les interventions annulées dont la demande précède cette date
    -- p_interventions : nombre d'interventions archivées
    -- p_historiques   : nombre de lignes d'historique archivées
    -- p_taille_lot    : nombre d'interventions traitées par lot (un commit par lot)
    -- p_commit        : FALSE dans les tests, pour que tout soit annulé à la fin du test
    -- Les paramètres facultatifs sont en dernier : un appel JDBC positionnel peut les omettre.
    PROCEDURE archiver_interventions(
        p_date_limite   IN  DATE,
        p_interventions OUT NUMBER,
        p_historiques   OUT NUMBER,
        p_taille_lot    IN  PLS_INTEGER DEFAULT 10000,
        p_commit        IN  BOOLEAN     DEFAULT TRUE
    );

END pkg_maintenance;
/

CREATE OR REPLACE PACKAGE BODY pkg_maintenance AS

    TYPE t_ids IS TABLE OF intervention.id_intervention%TYPE;

    -- Le journal est écrit dans une transaction autonome : il est conservé
    -- même quand le traitement est annulé (ROLLBACK) après une erreur.
    FUNCTION ouvrir_journal(p_date_limite IN DATE) RETURN NUMBER IS
        PRAGMA AUTONOMOUS_TRANSACTION;
        v_id journal_archivage.id_journal%TYPE;
    BEGIN
        INSERT INTO journal_archivage (date_debut, date_limite, statut)
        VALUES (SYS_EXTRACT_UTC(SYSTIMESTAMP), p_date_limite, 'EN_COURS')
        RETURNING id_journal INTO v_id;
        COMMIT;
        RETURN v_id;
    END ouvrir_journal;

    PROCEDURE fermer_journal(p_id IN NUMBER, p_statut IN VARCHAR2, p_interventions IN NUMBER,
                             p_historiques IN NUMBER, p_message IN VARCHAR2) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        UPDATE journal_archivage
           SET date_fin = SYS_EXTRACT_UTC(SYSTIMESTAMP),
               statut = p_statut,
               interventions = p_interventions,
               historiques = p_historiques,
               message = SUBSTR(p_message, 1, 4000)
         WHERE id_journal = p_id;
        COMMIT;
    END fermer_journal;

    PROCEDURE archiver_interventions(
        p_date_limite   IN  DATE,
        p_interventions OUT NUMBER,
        p_historiques   OUT NUMBER,
        p_taille_lot    IN  PLS_INTEGER DEFAULT 10000,
        p_commit        IN  BOOLEAN     DEFAULT TRUE
    ) IS
        v_journal NUMBER;
        v_ids     t_ids;
        v_limite  TIMESTAMP;
    BEGIN
        p_interventions := 0;
        p_historiques := 0;
        v_journal := ouvrir_journal(p_date_limite);
        SAVEPOINT debut_lot;   -- rend le ROLLBACK TO du gestionnaire d'erreur toujours valide

        IF p_date_limite IS NULL OR p_date_limite > TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20010, 'La date limite d''archivage doit être renseignée et passée.');
        END IF;
        IF p_taille_lot IS NULL OR p_taille_lot < 1 THEN
            RAISE_APPLICATION_ERROR(-20011, 'La taille de lot doit être positive.');
        END IF;
        v_limite := CAST(p_date_limite AS TIMESTAMP);

        LOOP
            SAVEPOINT debut_lot;

            -- Les lignes archivées sont supprimées : chaque lot relit simplement les suivantes
            SELECT id_intervention BULK COLLECT INTO v_ids
              FROM intervention
             WHERE (statut = 'TERMINEE' AND date_fin < v_limite)
                OR (statut = 'ANNULEE' AND date_demande < v_limite)
             FETCH FIRST p_taille_lot ROWS ONLY;

            EXIT WHEN v_ids.COUNT = 0;

            FORALL i IN 1 .. v_ids.COUNT
                INSERT INTO intervention_archive (
                    id_intervention, numero, titre, description, priorite, statut, date_demande,
                    date_planifiee, date_debut, date_fin, temps_passe_min, compte_rendu, motif_annulation,
                    version, id_equipement, id_demandeur, id_technicien, id_modifie_par, date_archivage)
                SELECT id_intervention, numero, titre, description, priorite, statut, date_demande,
                       date_planifiee, date_debut, date_fin, temps_passe_min, compte_rendu, motif_annulation,
                       version, id_equipement, id_demandeur, id_technicien, id_modifie_par,
                       SYS_EXTRACT_UTC(SYSTIMESTAMP)
                  FROM intervention
                 WHERE id_intervention = v_ids(i);

            FORALL i IN 1 .. v_ids.COUNT
                INSERT INTO historique_statut_archive (
                    id_historique, ancien_statut, nouveau_statut, date_changement, id_intervention, id_auteur)
                SELECT id_historique, ancien_statut, nouveau_statut, date_changement, id_intervention, id_auteur
                  FROM historique_statut
                 WHERE id_intervention = v_ids(i);
            p_historiques := p_historiques + SQL%ROWCOUNT;

            -- L'historique d'abord : il référence l'intervention
            FORALL i IN 1 .. v_ids.COUNT
                DELETE FROM historique_statut WHERE id_intervention = v_ids(i);

            FORALL i IN 1 .. v_ids.COUNT
                DELETE FROM intervention WHERE id_intervention = v_ids(i);

            p_interventions := p_interventions + v_ids.COUNT;
            IF p_commit THEN
                COMMIT;   -- un lot archivé est définitivement acquis, même si un lot suivant échoue
            END IF;
        END LOOP;

        fermer_journal(v_journal, 'SUCCES', p_interventions, p_historiques, NULL);
    EXCEPTION
        WHEN OTHERS THEN
            -- Annule le lot en cours (les lots déjà validés restent archivés), journalise, puis remonte l'erreur
            ROLLBACK TO debut_lot;
            fermer_journal(v_journal, 'ECHEC', p_interventions, p_historiques,
                           SQLERRM || CHR(10) || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
            RAISE;
    END archiver_interventions;

END pkg_maintenance;
